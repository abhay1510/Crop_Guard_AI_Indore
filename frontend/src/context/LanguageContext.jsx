const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const saved = localStorage.getItem('cg_language');
    return ['en', 'hi', 'mr'].includes(saved) ? saved : 'en';
  });
  const setLanguage = useCallback((next) => {
    if (!['en', 'hi', 'mr'].includes(next)) return;
    localStorage.setItem('cg_language', next);
    setLanguageState(next);
  }, []);
  useEffect(() => {
    document.documentElement.lang = language === 'hi' ? 'hi' : language === 'mr' ? 'mr' : 'en';
  }, [language]);
  const translate = useCallback((text) => {
    if (typeof text !== 'string' || language === 'en') return text;
    const direct = translations[language]?.[text];
    if (direct) return direct;
    const crop = (label) => translations[language]?.[label] || label;
    if (text === 'Scan failed or incomplete. Upload the image again or inspect this zone manually.') {
      return language === 'hi'
        ? 'स्कैन विफल या अधूरा है। छवि फिर से अपलोड करें या इस क्षेत्र की स्वयं जाँच करें।'
        : 'स्कॅन अयशस्वी किंवा अपूर्ण आहे. प्रतिमा पुन्हा अपलोड करा किंवा या क्षेत्राची स्वतः तपासणी करा.';
    }
    let match = text.match(/^The model recognised this as "(.+)", which does not match this field's crop\. Retake a close-up of a single leaf of the field crop, or inspect manually\.$/);
    if (match) return language === 'hi'
      ? `मॉडल ने इसे "${crop(match[1])}" के रूप में पहचाना, जो इस खेत की फसल से मेल नहीं खाता। खेत की फसल की एक पत्ती की नज़दीकी तस्वीर लें या स्वयं जाँचें।`
      : `मॉडेलने याला "${crop(match[1])}" म्हणून ओळखले, जे या शेतातील पिकाशी जुळत नाही. शेतातील पिकाच्या एका पानाचा जवळून फोटो घ्या किंवा स्वतः तपासा.`;
    if (text === 'Result is uncertain. Retake a clearer close-up image or inspect manually.') return language === 'hi'
      ? 'परिणाम अनिश्चित है। अधिक स्पष्ट नज़दीकी छवि लें या स्वयं जाँचें।'
      : 'निकाल अनिश्चित आहे. अधिक स्पष्ट जवळची प्रतिमा घ्या किंवा स्वतः तपासा.';
    if (text === 'No problem detected. Continue routine monitoring.') return language === 'hi'
      ? 'कोई समस्या नहीं मिली। नियमित निगरानी जारी रखें।'
      : 'समस्या आढळली नाही. नियमित निरीक्षण सुरू ठेवा.';
    if (text === 'Moderate confidence. Take another image or do a quick visual check.') return language === 'hi'
      ? 'विश्वास स्तर मध्यम है। एक और छवि लें या जल्दी से दृश्य जाँच करें।'
      : 'विश्वास पातळी मध्यम आहे. आणखी एक प्रतिमा घ्या किंवा पटकन दृश्य तपासणी करा.';
    match = text.match(/^Suspected "(.+)"\. Verify symptoms on-site and consult crop-specific agronomic guidance before any treatment\.$/);
    if (match) return language === 'hi'
      ? `"${crop(match[1])}" की आशंका है। लक्षणों की खेत पर पुष्टि करें और उपचार से पहले फसल-विशिष्ट कृषि सलाह लें।`
      : `"${crop(match[1])}" चा संशय आहे. लक्षणे शेतावर तपासा आणि उपचारापूर्वी पिकानुसार कृषी मार्गदर्शन घ्या.`;
    match = text.match(/^Possible "(.+)" \(moderate confidence\)\. Inspect plants in this zone and take more images\.$/);
    if (match) return language === 'hi'
      ? `"${crop(match[1])}" की संभावना है (मध्यम विश्वास)। इस क्षेत्र के पौधों की जाँच करें और अधिक तस्वीरें लें।`
      : `"${crop(match[1])}" शक्य आहे (मध्यम विश्वास). या क्षेत्रातील झाडे तपासा आणि आणखी प्रतिमा घ्या.`;
    return text;
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: translate,
    languageName: language === 'hi' ? 'Hindi' : language === 'mr' ? 'Marathi' : 'English',
  }), [language, setLanguage, translate]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function LanguageSelect({ className = '' }) {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className={`flex items-center gap-2 text-xs text-emerald-100/60 ${className}`}>
      <span className="hidden sm:inline">{t('Language')}</span>
      <select aria-label={t('Language')} className="input !w-auto !py-2 !pl-2 !pr-7 text-xs" value={language} onChange={(event) => setLanguage(event.target.value)}>
        <option value="en">English</option>
        <option value="hi">हिन्दी</option>
        <option value="mr">मराठी</option>
      </select>
    </label>
  );
}
